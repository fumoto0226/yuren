const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const path=require('node:path');
const inputs=['body','width','arms','legs','head'].map(key=>({dataset:{control:key},value:'100'}));
const context=vm.createContext({document:{querySelector:()=>({setAttribute(){}}),querySelectorAll:()=>inputs},requestAnimationFrame:()=>1,console});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../script.js'),'utf8').split('resetButton.addEventListener')[0],context);
const result=vm.runInContext(`(()=>{
  activeDecorationCategory='pants';
  selectedDecorations.shirt='red-tee';selectedDecorations.pants='navy-jumpsuit';
  selectedDecorations.outerwear='green-vest';selectedDecorations.shoes='brown-boots';
  selectedDecorations.gloves='plain';selectedDecorations.neck='scarf';
  applyDecorationSelection('suit','milk-frog');
  const suit={...selectedDecorations},color=skinColor(),hat=helmetVisible;
  const warp=buildWarp({body:100,width:100,arms:100,legs:100,head:100});
  const belly=torsoGarmentPath(milkFrogBellySource,warp);
  applyDecorationSelection('shirt','red-tee');
  const individual={...selectedDecorations},normalColor=skinColor();
  applyDecorationSelection('suit','milk-frog');
  applyDecorationSelection('suit',null);
  return {suit,color,hat,belly,individual,normalColor,removed:{...selectedDecorations}};
})()`,context);
assert.equal(result.suit.suit,'milk-frog');
assert.ok(Object.entries(result.suit).every(([key,value])=>key==='suit'||value===null),'A suit replaces every clothing slot');
assert.equal(result.color,'#e9ab24');assert.equal(result.hat,false);
assert.ok(result.belly.length>20&&!/NaN|Infinity/.test(result.belly));
assert.equal(result.individual.suit,null,'Choosing a single item exits the suit');
assert.equal(result.individual.shirt,'red-tee');assert.equal(result.normalColor,'#C5C5C5');
assert.ok(Object.values(result.removed).every(value=>value===null),'Removing the suit clears the complete look');
console.log('Milk frog equips as one complete look, clears every clothing slot and restores normal skin when exited.');
