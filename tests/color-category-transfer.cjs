const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const c=vm.createContext({Date});
vm.runInContext(fs.readFileSync('color-category-transfer.js','utf8'),c);
const api=vm.runInContext('ColorCategoryTransfer',c);
const old={shirt:[{id:'tee',name:'旧上衣'},{id:'coat',name:'外套'},{id:'gone',name:'已删除'}]};
const groups={shirt:[['basic','基础款',['tee']]]};
const state={categories:[{id:'a',name:'推荐',color:'#ff6699'}],assignments:{'shirt:item:tee':'a','shirt:item:coat':'a','shirt:item:gone':'a','shirt:style:basic':'a'}};
const packed=api.pack(state,old,groups);
const current={shirt:[{id:'tee',name:'新上衣'},{id:'new',name:'新增上衣'}],outerwear:[{id:'coat',name:'外套'}]};
const nextGroups={shirt:[['basic','基础款',['tee','new']]]};
const result=api.inspect(packed,current,nextGroups);
assert.equal(result.applied,3);
assert.equal(result.missing[0],'已删除');
assert.equal(result.renamed[0],'旧上衣 → 新上衣');
assert.equal(result.moved.length,1);
assert.equal(result.changedStyles.length,1);
assert.equal(result.state.assignments['outerwear:item:coat'],'a');
assert.equal(result.state.assignments['shirt:item:gone'],'a');
assert.equal(result.state.assignments['shirt:item:new'],undefined);
assert.ok(result.added.includes('新增上衣'));
const roundtrip=api.pack(result.state,current,nextGroups);
assert.ok(roundtrip.catalog.some(item=>item.key==='shirt:item:gone'));
assert.equal(api.inspect(roundtrip,old,groups).state.assignments['shirt:item:gone'],'a');
assert.throws(()=>api.inspect({...packed,version:999},current,nextGroups));
assert.throws(()=>api.inspect({...packed,categories:[{id:'a',name:'x',color:'red'}]},current,nextGroups));
assert.throws(()=>api.inspect({...packed,assignments:{'shirt:item:tee':'unknown'}},current,nextGroups));
assert.throws(()=>api.inspect({...packed,categories:[...packed.categories,...packed.categories]},current,nextGroups));
console.log('Transfer matches stable IDs, renamed/moved items, new items, changed styles and missing-item roundtrips; invalid files are rejected.');
